const RETAIL_UNITS = new Set(['pc', 'pack', 'kg', 'g', 'meter', 'liter', 'sack', 'box', 'sheet', 'tasa', 'tray', 'ream']);

function formatToday(): string {
  return new Date().toLocaleDateString('en-US', {
    month: 'short',
    day: '2-digit',
    year: 'numeric',
  });
}

function isValidStockNumber(value: unknown): boolean {
  const number = Number(value);
  return Number.isFinite(number) && number >= 0 && Number.isInteger(number * 1000);
}

function isValidMoney(value: unknown): boolean {
  const number = Number(value);
  return Number.isFinite(number) && number >= 0 && Number.isInteger(number * 100);
}

function makeSyntheticSku(name: string, exceptId?: string): string {
  const slug = name.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toUpperCase().replace(/[^A-Z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 36) || 'ITEM';
  let sku = `GEN-ST01-${slug}`;
  let suffix = 2;
  let match = sqlite.prepare('SELECT id FROM inventory_items WHERE sku = ? LIMIT 1').get(sku) as { id: string } | undefined;
  while (match && match.id !== exceptId) {
    sku = `GEN-ST01-${slug}-${suffix++}`;
    match = sqlite.prepare('SELECT id FROM inventory_items WHERE sku = ? LIMIT 1').get(sku) as { id: string } | undefined;
  }
  return sku;
}

function formatDateLabel(iso: string | null): string {
  if (!iso) return 'Active now';
  const parsed = new Date(iso);
  if (Number.isNaN(parsed.getTime())) return iso;
  return parsed.toLocaleDateString('en-US', {
    month: 'short',
    day: '2-digit',
    year: 'numeric',
  });
}

function formatInventoryRow(row: Record<string, unknown>) {
  return {
    id: String(row.id),
    sku: String(row.sku),
    name: String(row.name),
    category: String(row.category),
    location: String(row.location ?? ''),
    supplier: String(row.supplier ?? ''),
    quantity: Number(row.quantity ?? 0),
    reorderPoint: Number(row.reorder_point ?? 0),
    unitCost: Number(row.unit_cost ?? 0),
    unitPrice: Number(row.unit_price ?? 0),
    aliases: JSON.parse(String(row.aliases_json || '[]')) as string[],
    baseUnit: String(row.base_unit ?? 'pc'),
    sellingUnit: String(row.selling_unit ?? row.base_unit ?? 'pc'),
    ...(row.parent_product_id ? { parentProductId: String(row.parent_product_id) } : {}),
    conversionFactor: Number(row.conversion_factor ?? 1),
    isAutoGeneratedSku: Boolean(row.is_auto_generated_sku),
    lastUpdated: String(row.last_updated ?? ''),
  };
}

function formatSaleRow(row: Record<string, unknown>) {
  const storedStatus = String(row.status ?? 'COMPLETED');
  const statusLabels: Record<string, string> = {
    COMPLETED: 'Completed', PENDING: 'Pending', REFUNDED: 'Refunded',
  };
  return {
    id: String(row.id),
    orderNumber: String(row.order_number),
    customerName: String(row.customer_name),
    channel: String(row.channel),
    ...(row.inventory_item_id ? { inventoryItemId: String(row.inventory_item_id) } : {}),
    itemName: String(row.item_name),
    ...(row.sku ? { sku: String(row.sku) } : {}),
    quantity: Number(row.quantity ?? 1),
    unitPrice: Number(row.unit_price ?? 0),
    unitSold: String(row.unit_sold ?? 'pc'),
    unitCostSnapshot: Number(row.unit_cost_snapshot ?? 0),
    discountAmount: Number(row.discount_amount ?? 0),
    amountPaid: Number(row.amount_paid ?? 0),
    ...(row.customer_id ? { customerId: String(row.customer_id) } : {}),
    recordSource: String(row.record_source ?? 'POS_LIVE'),
    deductStock: Boolean(row.deduct_stock ?? 1),
    extraMetadata: JSON.parse(String(row.extra_metadata || '{}')) as Record<string, unknown>,
    status: statusLabels[storedStatus] ?? storedStatus,
    date: String(row.date),
    ...(row.notes ? { notes: String(row.notes) } : {}),
  };
}

