workspaceRouter.patch('/sales/:id', requireAuth, (req, res, next) => {
  try {
    const { id } = req.params;
    const existing = sqlite.prepare('SELECT * FROM sales WHERE id = ?').get(id);
    if (!existing) throw new HttpError(404, 'sale not found');
    const b = req.body ?? {};
    const immutableAmountChanges =
      (b.quantity !== undefined && Number(b.quantity) !== Number(existing.quantity)) ||
      (b.unitPrice !== undefined && Math.round(Number(b.unitPrice) * 100) !== Math.round(Number(existing.unit_price) * 100)) ||
      (b.discountAmount !== undefined && Math.round(Number(b.discountAmount) * 100) !== Math.round(Number(existing.discount_amount) * 100)) ||
      (b.inventoryItemId !== undefined && String(b.inventoryItemId ?? '') !== String(existing.inventory_item_id ?? ''));
    if (immutableAmountChanges) throw new HttpError(409, 'sale line amounts and inventory links are immutable; void and re-enter the sale');
    if (existing.customer_id && ['UTANG', 'PARTIAL'].includes(String(existing.status)) &&
      ['status', 'quantity', 'unitPrice', 'discountAmount', 'amountPaid', 'customerId'].some((field) => b[field] !== undefined && String(b[field]) !== String(existing[field === 'unitPrice' ? 'unit_price' : field === 'discountAmount' ? 'discount_amount' : field === 'amountPaid' ? 'amount_paid' : field === 'customerId' ? 'customer_id' : field]))) {
      throw new HttpError(409, 'credit sale amounts and status are ledger-backed and cannot be edited');
    }
    const nextStatus = b.status !== undefined ? String(b.status).toUpperCase() : String(existing.status);
    if (!['COMPLETED', 'UTANG', 'PARTIAL', 'FOR_DELIVERY', 'VOIDED', 'REFUNDED', 'PENDING'].includes(nextStatus)) {
      throw new HttpError(400, 'status is invalid');
    }
    if (nextStatus === 'VOIDED' || nextStatus === 'REFUNDED') {
      throw new HttpError(409, 'use DELETE to void a sale; refunded sales require a refund ledger entry');
    }
    const oldStatus = String(existing.status).toUpperCase();
    if (oldStatus !== nextStatus && !(oldStatus === 'PENDING' && nextStatus === 'COMPLETED')) {
      throw new HttpError(409, 'sale status transition is not allowed');
    }
    const nextQty = b.quantity !== undefined ? Number(b.quantity) : Number(existing.quantity);
    const nextPrice = b.unitPrice !== undefined ? Number(b.unitPrice) : Number(existing.unit_price);
    const nextDiscount = b.discountAmount !== undefined ? Number(b.discountAmount) : Number(existing.discount_amount);
    const nextPaid = nextStatus === 'COMPLETED'
      ? nextQty * nextPrice - nextDiscount
      : b.amountPaid !== undefined ? Number(b.amountPaid) : Number(existing.amount_paid);
    if (![nextQty, nextPrice].every(Number.isFinite) || nextQty <= 0 || !Number.isInteger(nextQty * 1000) || !isValidMoney(nextPrice) || !isValidMoney(nextDiscount) || !isValidMoney(nextPaid) || nextDiscount > nextQty * nextPrice || nextPaid > nextQty * nextPrice - nextDiscount) {
      throw new HttpError(400, 'sale amounts are invalid');
    }
    sqlite.prepare(
      `UPDATE sales SET order_number = ?, customer_name = ?, channel = ?, inventory_item_id = ?, item_name = ?, sku = ?, quantity = ?, unit_price = ?, unit_sold = ?, unit_cost_snapshot = ?, discount_amount = ?, amount_paid = ?, customer_id = ?, status = ?, record_source = ?, deduct_stock = ?, extra_metadata = ?, date = ?, notes = ? WHERE id = ?`
    ).run(
      b.orderNumber !== undefined ? String(b.orderNumber) : existing.order_number,
      b.customerName !== undefined ? String(b.customerName) : existing.customer_name,
      b.channel !== undefined ? String(b.channel) : existing.channel,
      b.inventoryItemId !== undefined ? b.inventoryItemId || null : existing.inventory_item_id,
      b.itemName !== undefined ? String(b.itemName) : existing.item_name,
      b.sku !== undefined ? b.sku ?? null : existing.sku,
      nextQty,
      nextPrice,
      b.unitSold !== undefined ? String(b.unitSold) : existing.unit_sold,
      b.unitCostSnapshot !== undefined ? Number(b.unitCostSnapshot) : existing.unit_cost_snapshot,
      nextDiscount,
      nextPaid,
      b.customerId !== undefined ? b.customerId || null : existing.customer_id,
      nextStatus,
      b.recordSource !== undefined ? String(b.recordSource) : existing.record_source,
      b.deductStock !== undefined ? (b.deductStock ? 1 : 0) : existing.deduct_stock,
      b.extraMetadata !== undefined ? JSON.stringify(b.extraMetadata) : existing.extra_metadata,
      b.date !== undefined ? String(b.date) : existing.date,
      b.notes !== undefined ? b.notes ?? null : existing.notes,
      id
    );
    const updated = sqlite.prepare('SELECT * FROM sales WHERE id = ?').get(id)!;
    res.json(formatSaleRow(updated));
  } catch (err) {
    next(err);
  }
});

workspaceRouter.delete('/sales/:id', requireAuth, (req, res, next) => {
  try {
    const { id } = req.params;
    const sale = sqlite.prepare('SELECT * FROM sales WHERE id = ?').get(id);
    if (!sale) throw new HttpError(404, 'sale not found');
    if (sale.customer_id && ['UTANG', 'PARTIAL'].includes(String(sale.status))) {
      throw new HttpError(409, 'credit sale cannot be voided until its ledger balance is settled');
    }
    withSqliteTransaction(() => {
      if (sale.deduct_stock && sale.inventory_item_id) {
        sqlite.prepare('UPDATE inventory_items SET quantity = quantity + ?, last_updated = ? WHERE id = ?')
          .run(Number(sale.quantity), formatToday(), String(sale.inventory_item_id));
      }
      sqlite.prepare("UPDATE sales SET status = 'VOIDED', deduct_stock = 0 WHERE id = ?").run(id);
    });
    res.status(204).send();
  } catch (err) {
    next(err);
  }
});

workspaceRouter.post('/sales/notebook-import', requireAuth, (req, res, next) => {
  try {
    const importId = String(req.body?.importId ?? '').trim().replace(/[^A-Za-z0-9_-]/g, '-').slice(0, 48);
    const rows = req.body?.rows;
    if (!importId) throw new HttpError(400, 'importId is required');
    if (!Array.isArray(rows) || rows.length > 5000) throw new HttpError(400, 'rows must be an array with at most 5000 entries');

    const result = withSqliteTransaction(() => {
      const created: string[] = [];
      const skipped: Array<{ row: number; reason: string }> = [];
      for (const [index, raw] of rows.entries()) {
        const rowNumber = Number(raw?.rowNumber ?? index + 1);
        const name = String(raw?.product ?? '').trim();
        const date = String(raw?.date ?? '').trim();
        const quantity = Number(raw?.quantity ?? raw?.qty);
        const recordedSales = Math.round(Number(raw?.sales) * 100) / 100;
        if (!name || !date || !Number.isFinite(quantity) || quantity <= 0 || !Number.isFinite(recordedSales) || recordedSales < 0) {
          skipped.push({ row: rowNumber, reason: 'date, product, positive quantity, and non-negative sales are required' });
          continue;
        }
        const orderNumber = `NB-${importId}-${index + 1}`;
        if (sqlite.prepare('SELECT id FROM sales WHERE order_number = ? LIMIT 1').get(orderNumber)) {
          skipped.push({ row: rowNumber, reason: 'row was already imported' });
          continue;
        }

        let product = sqlite.prepare('SELECT * FROM inventory_items WHERE lower(trim(name)) = lower(trim(?)) LIMIT 1').get(name);
        if (!product) {
          const alias = sqlite.prepare(
            `SELECT i.* FROM inventory_items i, json_each(i.aliases_json) a WHERE lower(trim(CAST(a.value AS TEXT))) = lower(trim(?)) LIMIT 1`
          ).get(name);
          product = alias;
        }
        if (!product) {
          const slug = name.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toUpperCase().replace(/[^A-Z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 36) || 'ITEM';
          let sku = `GEN-ST01-${slug}`;
          let suffix = 2;
          while (sqlite.prepare('SELECT id FROM inventory_items WHERE sku = ?').get(sku)) sku = `GEN-ST01-${slug}-${suffix++}`;
          const productId = newId();
          sqlite.prepare(
            `INSERT INTO inventory_items (id, sku, name, category, location, supplier, quantity, reorder_point, unit_cost, unit_price, aliases_json, base_unit, conversion_factor, is_auto_generated_sku, last_updated)
             VALUES (?, ?, ?, 'General', '', '', 0, 0, 0, 0, '[]', 'pc', 1, 1, ?)`
          ).run(productId, sku, name, formatToday());
          product = sqlite.prepare('SELECT * FROM inventory_items WHERE id = ?').get(productId);
        }
        if (!product) throw new HttpError(500, 'could not prepare notebook product record');

        const unitPrice = Math.ceil((recordedSales / quantity) * 100) / 100;
        const gross = Math.round(quantity * unitPrice * 100) / 100;
        const discount = Math.max(0, Math.round((gross - recordedSales) * 100) / 100);
        const saleId = newId();
        const now = new Date().toISOString();
        sqlite.prepare(
          `INSERT INTO sales (id, order_number, customer_name, channel, inventory_item_id, item_name, sku, quantity, unit_price, unit_sold, unit_cost_snapshot, discount_amount, amount_paid, status, record_source, deduct_stock, extra_metadata, date, notes, created_at)
           VALUES (?, ?, '', 'Notebook Archive', ?, ?, ?, ?, ?, ?, ?, ?, ?, 'COMPLETED', 'NOTEBOOK_ARCHIVE', 0, ?, ?, ?, ?)`
        ).run(
          saleId, orderNumber, product.id, String(product.name), String(product.sku), quantity,
          unitPrice, String(product.base_unit ?? 'pc'), 0, discount,
          recordedSales, JSON.stringify({ importId, rowNumber, originalSales: recordedSales, historicalCostUnknown: true }),
          date, `Imported from notebook ${importId}`, now
        );
        created.push(saleId);
      }
      return { created, skipped };
    });
    res.status(200).json({ importId, imported: result.created.length, skipped: result.skipped, saleIds: result.created });
  } catch (err) { next(err); }
});

